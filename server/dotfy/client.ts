import crypto from 'node:crypto';
import {DOTFY_OPERATIONS,type DotfyOperation} from './operations.ts';
export const DOTFY_BASE_URL='https://app.dotfy.com.br';
export class DotfyError extends Error{
 constructor(message:string,public status=502,public code='DOTFY_ERROR',public ambiguous=false){super(message);}
}
export function normalizeDotfyPhone(value:unknown){let digits=String(value??'').replace(/\D/g,'');if((digits.length===12||digits.length===13)&&digits.startsWith('55'))digits=digits.slice(2);if(!/^\d{10,11}$/.test(digits))throw new DotfyError('Telefone deve conter DDD e 10 ou 11 dígitos.',400,'INVALID_PHONE');return digits;}
export function paidCharge(value:any){return value?.isPaid===true||['PAID','COMPLETED'].includes(String(value?.status).toUpperCase());}
export function verifyDotfySignature(raw:string,header:string,secret:string,now=Date.now()){
 if(!raw||!header||!secret)return false;
 const match=/^t=(\d{13}),v1=([a-fA-F0-9]{64})$/.exec(header.trim());
 if(!match||Math.abs(now-Number(match[1]))>300000)return false;
 const expected=crypto.createHmac('sha256',secret).update(`${match[1]}.${raw}`).digest();
 return crypto.timingSafeEqual(expected,Buffer.from(match[2],'hex'));
}
export function normalizeChargePayload(body:any){
 if(!body||typeof body!=='object')throw new DotfyError('Corpo de cobrança inválido.',400,'INVALID_CHARGE');
 const value=Number(body.value);
 if(!Number.isFinite(value)||value<=0||value>1000000||Math.abs(value*100-Math.round(value*100))>1e-6)throw new DotfyError('Depósito deve ter um valor positivo em reais, com até duas casas decimais.',400,'INVALID_AMOUNT');
 const out={...body,value};
 // Callback destination belongs to server configuration, never a player body/Host header.
 const callback=process.env.DOTFY_WEBHOOK_URL || (process.env.APP_URL?.startsWith('https://')?process.env.APP_URL.replace(/\/$/,'')+'/api/webhooks/dotfy':'');
 delete out.webhook_url;
 if(callback){const u=new URL(callback);if(u.protocol!=='https:'||u.username||u.password)throw new DotfyError('Configure uma URL HTTPS pública para webhook.',503,'INVALID_WEBHOOK_URL');out.webhook_url=u.toString();}
 if(out.expiresIn!==undefined&&(!Number.isInteger(out.expiresIn)||out.expiresIn<60||out.expiresIn>86400))throw new DotfyError('Validade PIX deve ficar entre 60 e 86400 segundos.',400,'INVALID_EXPIRY');
 if(out.customer?.phone)out.customer={...out.customer,phone:normalizeDotfyPhone(out.customer.phone)};
 // correlationID is generated by Dotfy; it is not upstream idempotency.
 delete out.correlationID;
 return out;
}
const buckets=new Map<string,number[]>();
export function createDotfyTransport(fetcher:typeof fetch=fetch){
 return async(input:string|URL,init:RequestInit={})=>{
  const url=new URL(input,DOTFY_BASE_URL);const method=(init.method||'GET').toUpperCase();
  if(url.origin!==DOTFY_BASE_URL||!url.pathname.startsWith('/api/')||url.username||url.password)throw new DotfyError('Destino Dotfy inválido.',400,'INVALID_DESTINATION');
  const headers=new Headers(init.headers);const authorization=headers.get('Authorization')||'';
  if(!/^Bearer\s+\S+$/i.test(authorization))throw new DotfyError('Chave Dotfy do servidor não configurada.',503,'DOTFY_NOT_CONFIGURED');
  let body=init.body;
  if(method==='POST'&&url.pathname==='/api/charges'&&typeof body==='string')body=JSON.stringify(normalizeChargePayload(JSON.parse(body)));
  // One shared per-key budget across games. No automatic retry of money writes.
  const key=crypto.createHash('sha256').update(authorization).digest('hex');const now=Date.now();
  const times=(buckets.get(key)||[]).filter(t=>now-t<60000);
  if(times.length>=600)return Response.json({error:'Limite compartilhado Dotfy atingido.',code:'LOCAL_RATE_LIMIT'},{status:429,headers:{'Retry-After':String(Math.ceil((60000-(now-times[0]))/1000))}});
  const op=Object.values(DOTFY_OPERATIONS).find((v:any)=>v.method===method&&new RegExp('^'+v.path.replace(/\{[^}]+\}/g,'[^/]+')+'$').test(url.pathname)) as any;
  const routeKey=key+':'+method+':'+(op?.path||url.pathname);
  const routeTimes=(buckets.get(routeKey)||[]).filter(t=>now-t<60000);
  if(op?.rateLimit?.scope==='route'&&routeTimes.length>=op.rateLimit.limit)return Response.json({error:'Limite da operação Dotfy atingido.',code:'LOCAL_ROUTE_RATE_LIMIT'},{status:429,headers:{'Retry-After':'60'}});
  times.push(now);buckets.set(key,times);routeTimes.push(now);buckets.set(routeKey,routeTimes);
  let response:Response;
  try{response=await fetcher(url,{...init,body,headers,redirect:'error',signal:init.signal?AbortSignal.any([init.signal,AbortSignal.timeout(12000)]):AbortSignal.timeout(12000)});}catch{throw new DotfyError(method==='GET'?'Dotfy indisponível.':'Resultado Dotfy não confirmado. Consulte e concilie antes de reenviar.',503,'DOTFY_UNCONFIRMED',method!=='GET');}
  return response;
 };
}
export const dotfyFetch=createDotfyTransport();
export class DotfyClient{
 constructor(private apiKey:()=>Promise<string>,private transport:ReturnType<typeof createDotfyTransport>=dotfyFetch){}
 async execute(operation:DotfyOperation,input:{path?:Record<string,string>;query?:Record<string,unknown>;body?:unknown}={}){
  const op=DOTFY_OPERATIONS[operation] as any;if(!op)throw new DotfyError('Operação Dotfy desconhecida.',400,'INVALID_OPERATION');
  let path=op.path.replace(/\{([^}]+)\}/g,(_:string,k:string)=>{const v=input.path?.[k];if(!v)throw new DotfyError(`Parâmetro obrigatório: ${k}`,400,'MISSING_PARAMETER');return encodeURIComponent(v);});
  const url=new URL(path,DOTFY_BASE_URL);
  const query=input.query||{};
  if(Boolean(query.startDate)!==Boolean(query.endDate))throw new DotfyError('Informe startDate e endDate juntos.',400,'INVALID_DATE_RANGE');
  for(const p of op.parameters||[])if(p.in==='query'&&p.required&&query[p.name]===undefined)throw new DotfyError(`Parâmetro obrigatório: ${p.name}`,400,'MISSING_PARAMETER');
  for(const [k,v]of Object.entries(query))if(v!==undefined&&v!==null)url.searchParams.set(k,String(v));
  if(op.bodyRequired&&input.body===undefined)throw new DotfyError('Corpo obrigatório.',400,'MISSING_BODY');
  const form=typeof FormData!=='undefined'&&input.body instanceof FormData;
  const headers:Record<string,string>={Authorization:`Bearer ${await this.apiKey()}`};
  if(input.body!==undefined&&!form)headers['Content-Type']='application/json';
  const r=await this.transport(url,{method:op.method,headers,body:input.body===undefined?undefined:form?input.body as FormData:JSON.stringify(input.body)});
  const contentType=r.headers.get('content-type')||'';const data=contentType.includes('json')?await r.json():await r.text();
  if(!r.ok||data?.success===false)throw new DotfyError(typeof data?.error==='string'?data.error:`Dotfy HTTP ${r.status}`,r.ok?502:r.status,data?.code||data?.type||'DOTFY_ERROR',op.method!=='GET'&&r.status>=500);
  return data;
 }
}
